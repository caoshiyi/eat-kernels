    #pragma unroll
    for (int it = 0; it < 4; it++) {
        const int v_item = it * 128 + tid;
        const int row = v_item / 16;
        const int segment = v_item % 16;
        const long long token = bos + (long long)(chunk * 32 + row);
        const int token_valid = ((token < eos) ? 1 : 0);
        const long long v_src = (token * (long long)num_heads + (long long)head) * 128 + (long long)(segment * 8);
        asm volatile("cp.async.cg.shared::cta.global [%0], [%1], 16, %2;"
            :: "r"(sbase + (unsigned int)((segment >> 3) * 4096 + row * 128 + (((segment & 7) ^ (row & 7)) << 4))), "l"(v + v_src), "r"((token_valid != 0) ? 16 : 0));
