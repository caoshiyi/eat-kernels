// [startup] Start-up stagger model.  At t = 0 every CTA's five prep instances request their first g/k tiles (5 x 32 KB) and the compute warps read the
// 64 KB initial state: nCTA x 224 KB hit HBM at once.  The first-wave burst drains in X = T_lat + nCTA x bytes_per_CTA / BW_eff (fit: T_lat 3.25 us =
// first prep-chain latency, BW_eff 5.3 TB/s = 0.66 x HBM peak); instance i (1..4) joins at d_i = X (1 - R^i), R = 0.75 (each later instance enters when the
// backlog left by the earlier ones has decayed by R).  KSCALE: per-kernel fitted scale (cio 1.0; this plain kernel 0.75: shorter chain).  Instance 0 never waits.
#define BD_T_LAT_NS 3250.f
#define BD_BYTES_CTA 229376.f
#define BD_BW_BPNS 5300.f
#define BD_R 0.75f
__device__ __noinline__ void bd_stagger_wait(int inst_, int nit_) {
    if (nit_ == 0) return;   // this instance has no chunk in the CTA's first task
    long long t0_, t1_;
    asm volatile("mov.u64 %0, %globaltimer;" : "=l"(t0_)); t1_ = t0_;
    float rem_ = 1.f; for (int i_ = 0; i_ < inst_; i_++) rem_ *= BD_R;
    const long long dly_ = (long long)(0.75f * (BD_T_LAT_NS + (float)gridDim.x * (BD_BYTES_CTA / BD_BW_BPNS)) * (1.f - rem_));
    while (t1_ - t0_ < dly_) {
        __nanosleep(20);
        
        asm volatile("mov.u64 %0, %globaltimer;" : "=l"(t1_));
    }
}
