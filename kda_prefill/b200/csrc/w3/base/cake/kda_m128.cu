// ring slot load the tile with zero-fill instead (all 128 threads of the instance, 4 x 16 B each), after the chunk's prep is done (qk_full arrived: the v tile's smem region is prep scratch until then).
// Out of line, tail chunks only.  Arrival on v_full replaces the load warp's TMA arrival (init count 1).
__device__ __noinline__ void kda_tail_v(int sbase, const __nv_bfloat16* __restrict__ v, long long bos, long long eos, int chunk, int head, int num_heads, int tid,
                                        int vfree_a, int vfree_ph, int vfull_a, int bar_id) {
