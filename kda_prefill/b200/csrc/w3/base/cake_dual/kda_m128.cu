// of its row: one 16 B store per plane (st.global.v4), 64 B of a row per quad.
__device__ __forceinline__ void split_hilo(uint32_t xb, uint32_t yb, uint32_t& hi, uint32_t& lo) {
    const float x = __uint_as_float(xb), y = __uint_as_float(yb);
