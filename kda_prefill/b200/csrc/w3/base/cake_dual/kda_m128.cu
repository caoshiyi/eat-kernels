#define GSW(c) ((c) ^ ((((c) >> 5) & 1) << 2))  // [economist] gsw: conflict-free gate-prefix layout
// [hardening] partial last chunk of v: the TMA box would read the NEXT sequence's rows past the sequence end; NaN / Inf there would reach the state / output (NaN * 0 in the tensor-core products).  The prep warps of the
// ring slot load the tile with zero-fill instead (all 128 threads of the instance, 4 x 16 B each), after the chunk's prep is done (qk_full arrived: the v tile's smem region is prep scratch until then).
// Out of line, tail chunks only.  Arrival on v_full replaces the load warp's TMA arrival (init count 1).
__device__ __noinline__ void kda_tail_v(int sbase, const __nv_bfloat16* __restrict__ v, long long bos, long long eos, int chunk, int head, int num_heads, int tid,
                                        int vfree_a, int vfree_ph, int vfull_a, int bar_id) {
    mbarrier_wait(vfree_a, vfree_ph);
    #pragma unroll
    for (int it = 0; it < 4; it++) {
        const int v_item = it * 128 + tid;
        const int row = v_item / 16;
        const int segment = v_item % 16;
        const long long token = bos + (long long)(chunk * 32 + row);
        const int token_valid = ((token < eos) ? 1 : 0);
        const long long v_src = (token * (long long)num_heads + (long long)head) * 128 + (long long)(segment * 8);
        asm volatile("cp.async.cg.shared::cta.global [%0], [%1], 16, %2;"
            :: "r"(sbase + (unsigned int)((segment >> 3) * 4096 + row * 128 + (((segment & 7) ^ (row & 7)) << 4))), "l"(v + v_src), "r"((token_valid != 0) ? 16 : 0));
    }
    asm volatile("cp.async.commit_group;");
    asm volatile("cp.async.wait_group 0;");
    asm volatile("fence.proxy.async.shared::cta;" ::: "memory");
    { asm volatile("barrier.sync %0, 128;" :: "r"(bar_id) : "memory"); }
    if (tid == 0) mbarrier_arrive(vfull_a);
}

