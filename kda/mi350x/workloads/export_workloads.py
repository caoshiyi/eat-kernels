"""Writes workloads/workloads.json: the workload tables of benchmark/eval_kda_mi350x.py as data.

The eval's literals are the source of truth; this reads them with `ast` (no torch / GPU needed) so the JSON can be
regenerated and diffed:   python workloads/export_workloads.py [--check]
"""
import argparse
import ast
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EVAL = os.path.join(HERE, "..", "benchmark", "eval_kda_mi350x.py")
OUT = os.path.join(HERE, "workloads.json")

TABLES = {
    "PREFILL_WORKLOADS": "scored prefill steps: name -> [H, [[new tokens, has_initial_state, checkpoint offset], ...]] "
                         "(gen_prefill_batches.py --seed 1)",
    "DECODE_WORKLOADS": "scored decode / spec-verify steps: name -> [H, B, S]",
    "QUICK_PREFILL": "prefill subset of --quick",
    "QUICK_DECODE": "decode subset of --quick",
    "LEGACY_PREFILL": "phase-1 prefill no-regression gate: name -> sequence lengths (H = 12, contiguous state)",
    "LEGACY_DECODE": "phase-1 decode no-regression gate: name -> [H, B, S] (dense pools)",
    "DECODE_HELDOUT": "decode contract gate, held-out shapes: name -> [H, B, S]",
    "NUMERIC_PROBES": "numerics gate vs fp64: [name, H, sequences, input settings]",
}
CONSTANTS = ["D", "W", "LB", "NORM_EPS", "P_RTOL", "D_OUT_RTOL", "D_ST_RTOL", "SPEC_S", "SPEC_AL", "PAGE_PAD",
             "DEC_TOKENS_FIRST"]


def extract():
    tree = ast.parse(open(EVAL).read())
    wanted = set(TABLES) | set(CONSTANTS)
    found = {}
    for node in tree.body:
        if not (isinstance(node, ast.Assign) and len(node.targets) == 1):
            continue
        tgt = node.targets[0]
        names = [tgt.id] if isinstance(tgt, ast.Name) else [e.id for e in getattr(tgt, "elts", []) if isinstance(e, ast.Name)]
        if not names or not set(names) & wanted:
            continue
        # module-level literals with list repetition / unary minus only (no calls): evaluated without builtins
        value = eval(compile(ast.Expression(node.value), EVAL, "eval"), {"__builtins__": {}})
        for n, v in zip(names, value if len(names) > 1 else [value]):
            found[n] = v
    missing = [n for n in list(TABLES) + CONSTANTS if n not in found]
    if missing:
        sys.exit(f"not found in {EVAL}: {missing}")
    return {
        "source": "benchmark/eval_kda_mi350x.py (authoritative); generated by workloads/export_workloads.py",
        "constants": {n: found[n] for n in CONSTANTS},
        "tables": {n: {"description": d, "data": found[n]} for n, d in TABLES.items()},
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if workloads.json differs from the eval")
    args = ap.parse_args()
    text = json.dumps(extract(), indent=1) + "\n"
    if args.check:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("workloads.json up to date" if same else "workloads.json differs from the eval")
        return 0 if same else 1
    open(OUT, "w").write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
